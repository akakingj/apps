'use strict';
const assert = require('assert');
const { torque, Telemetry } = require('../../apps/cluster_redline/telemetry');
const { programme, display } = require('../../apps/cluster_redline/gear');
assert.strictEqual(torque(2807), 380);
assert.strictEqual(torque(2047), 0); assert.strictEqual(torque(1900), 0);
for (const raw of [4095, 65535, -1, null, undefined, '2807', NaN, 2807.5]) assert.strictEqual(torque(raw), null);
const t = new Telemetry(); assert.strictEqual(t.read(4200, 0).powerPS, null);
t.sample(2807, 100); const live = t.read(4200, 200);
assert.strictEqual(live.torqueNm, 380); assert(Math.abs(live.powerPS - 227.26) < 0.1);
assert.strictEqual(live.powerEstimated, true);
assert.strictEqual(t.read(4200, 2000).torqueNm, null, 'stale ECU torque must not look like live data');
t.sample(65535, 2100); assert.strictEqual(t.read(4200, 2100).powerPS, null);
assert.strictEqual(programme({ statusDriveMode: 'SPORT' }), 'S');
assert.strictEqual(programme({ statusManualMode: true }), 'M');
assert.strictEqual(programme({ statusActualGearDrive: 'G4', statusActualStageDrive: 'D' }), null);
assert.strictEqual(programme({ statusSport: 'INACTIVE' }), null);
assert.strictEqual(display('4', 'S', 'auto'), 'S4');
assert.strictEqual(display('4', 'D', 'auto'), 'D4');
assert.strictEqual(display('4', null, 'S'), 'S4');
assert.strictEqual(display('4', null, 'auto'), '4', 'never infer gearbox S from chassis Sport');
assert.strictEqual(display('P', 'S', 'S'), 'P');
console.log('PASS: ECU torque scaling, estimated PS, missing/stale samples, explicit gearbox modes and manual prefix');
